"""Build the iTerm2 dynamic profile and the zsh key bindings from keys.tsv.

The profile inherits everything from the current default iTerm2 profile and
adds Cmd/Option/F-key mappings that send CSI-u sequences Neovim reads as
<D-…>/<M-…>. A dynamic profile's "Keyboard Map" replaces the parent's whole
map, so the parent's own mappings are copied in first.

usage: make_profile.py keys.tsv profile.json cmd-keys.zsh
"""

import json
import plistlib
import sys
from pathlib import Path

GUID = "6F1A3C2E-9D4B-4E7A-8C55-1D2E3F4A5B6C"
NAME = "nvim IDE"
ACTION_ESCAPE_SEQUENCE = 10
PREFS = Path.home() / "Library/Preferences/com.googlecode.iterm2.plist"


def read_keys(path):
    rows = []
    for line in Path(path).read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        key, seq, widget, desc = line.split("\t")
        rows.append((key, seq, widget, desc))
    return rows


def parent_profile():
    if not PREFS.exists():
        return {"Name": "Default"}
    prefs = plistlib.loads(PREFS.read_bytes())
    profiles = prefs.get("New Bookmarks", [])
    default = prefs.get("Default Bookmark Guid")
    for p in profiles:
        if p.get("Guid") == default and p.get("Guid") != GUID:
            return p
    return profiles[0] if profiles else {"Name": "Default"}


def main(keys_path, profile_path, zsh_path):
    rows = read_keys(keys_path)
    parent = parent_profile()

    keymap = dict(parent.get("Keyboard Map", {}))
    for key, seq, _, desc in rows:
        keymap[key] = {"Action": ACTION_ESCAPE_SEQUENCE, "Text": seq}

    profile = {
        "Profiles": [
            {
                "Name": NAME,
                "Guid": GUID,
                "Dynamic Profile Parent Name": parent.get("Name", "Default"),
                "Keyboard Map": keymap,
                "Option Key Sends": 2,  # left Option = Meta (Esc+)
                "Right Option Key Sends": parent.get("Right Option Key Sends", 0),
            }
        ]
    }
    Path(profile_path).parent.mkdir(parents=True, exist_ok=True)
    Path(profile_path).write_text(json.dumps(profile, indent=2, ensure_ascii=False) + "\n")

    # The shell sees the same sequences: bind them so they don't print garbage.
    seen = set()
    lines = [
        "# Generated by nvim-ide/install.sh from iterm/keys.tsv.",
        "# Makes the Cmd/Option keys of the 'nvim IDE' iTerm2 profile harmless in zsh.",
    ]
    for _, seq, widget, desc in rows:
        if seq in seen:
            continue
        seen.add(seq)
        lines.append(f"bindkey '^[{seq}' {widget}  # {desc.split('  ')[0]}")
    Path(zsh_path).write_text("\n".join(lines) + "\n")

    print(f"iTerm2 profile '{NAME}' (parent: {parent.get('Name', 'Default')}): {profile_path}")
    print(GUID)


if __name__ == "__main__":
    main(*sys.argv[1:4])
